"""
Immutable benchmark metadata and the original BEVTSPD instance, generated by
reusing the existing generator rather than defining a new optimization problem.

Reference geometry follows Zhu, Boyles & Unnikrishnan (2024), Section 5.1.
Original authors' random seeds and instance files are NOT known; generated
cases are reference-geometry replicas, NOT the authors' original sample.
"""
struct BEVTSPDBenchmarkCase
    seed::Int
    customer_count::Int
    station_count::Int
    station_pool_count::Int
    paper_table::Symbol
    station_pool_coordinates::Matrix{Float64}
    instance::BEVTSPDInstance
end

"""
Station counts explicitly reported in Zhu et al. (2024), Table 6 (VNS) and
Table 4 (exact). For sizes outside the table return a clearly labeled
one-third *extrapolation*, not a reported original station count.
"""
function paper_reference_station_count(n::Int; table::Symbol = :vns_table6)
    n >= 1 || throw(ArgumentError("customer count must be positive"))
    if table == :vns_table6
        counts = Dict(5=>3, 6=>3, 7=>3, 10=>4, 15=>6, 20=>8, 25=>8)
    elseif table == :exact_table4
        counts = Dict(i=>3 for i in 5:10)
    else
        throw(ArgumentError("table must be :vns_table6 or :exact_table4"))
    end
    return get(counts, n, max(3, cld(n, 3)))
end

"""
Create a *paired, nested* station-availability case using an existing model.

For the same (seed, n, station_pool_count), customer coordinates, full station
pool, energy matrices and other parameters are identical. A case with k stations
uses the first k sites in the fixed pool. All sites are sampled uniformly in the
same 40 km x 40 km square as the paper. No extra artificial penalties are added.

Changing k is a test condition and must not be presented as a new model.
"""
function build_paired_bevtspd_case(
    seed::Integer,
    n::Int;
    station_count::Union{Nothing,Int} = nothing,
    station_pool_count::Union{Nothing,Int} = nothing,
    paper_table::Symbol = :vns_table6,
    truck_speed::Real = 40.0,
    drone_speed::Real = 60.0,
    truck_capacity::Real = 100.0,
    drone_capacity::Real = 20.0,
    shared_energy_factor::Real = 0.4,
    swap_service_time::Real = 2.0 / 60.0,
    launch_time::Real = 100.0 / 3600.0,
    retrieve_time::Real = 20.0 / 3600.0,
)
    n >= 1 || throw(ArgumentError("customer count must be positive"))
    reference_count = paper_reference_station_count(n; table = paper_table)
    k = isnothing(station_count) ? reference_count : station_count
    pool = isnothing(station_pool_count) ? max(k, reference_count) : station_pool_count
    0 <= k <= pool || throw(ArgumentError("require 0 <= station_count <= pool"))
    pool >= 0 || throw(ArgumentError("station pool must be nonnegative"))
    params = (
        truck_speed = truck_speed, drone_speed = drone_speed,
        truck_capacity = truck_capacity, drone_capacity = drone_capacity,
        shared_energy_factor = shared_energy_factor,
        swap_service_time = swap_service_time,
        launch_time = launch_time, retrieve_time = retrieve_time,
    )
    # IMPORTANT: generate the entire common pool BEFORE selecting the k sites.
    # This reuses the original project's verified seeded geometry generator.
    bank = generate_random_bevtspd_instance(
        seed, n; station_count = pool, params...,
    )
    customers = copy(bank.coordinates[bank.customer_nodes, :])
    station_pool = copy(bank.coordinates[bank.station_nodes, :])
    selected = copy(station_pool[1:k, :])
    instance = build_bevtspd_instance(customers, selected; params...)
    return BEVTSPDBenchmarkCase(
        Int(seed), n, k, pool, paper_table, station_pool, instance,
    )
end

"""
Objective and diagnostics for one fully specified route. Only makespan_h is
the primary optimization objective. Distances and station visits explain
where time losses occur; they are NOT additive components of makespan.
"""
function benchmark_route_metrics(
    case::BEVTSPDBenchmarkCase,
    truck_route::AbstractVector{Int},
    drone_route::AbstractVector{Int},
)
    inst = case.instance
    checked = evaluate_bevtspd_route(inst, truck_route, drone_route)
    if !checked.feasible
        return (
            feasible = false, makespan_h = Inf, station_visits = 0,
            truck_km = NaN, station_detour_km = NaN,
            swap_service_minutes = NaN,
        )
    end
    stations = Set(inst.station_nodes)
    core = [node for node in truck_route if !(node in stations)]
    path_km = sum(inst.truck_energy_matrix[truck_route[i], truck_route[i+1]]
                  for i in 1:(length(truck_route)-1); init=0.0)
    direct_km = sum(inst.truck_energy_matrix[core[i], core[i+1]]
                    for i in 1:(length(core)-1); init=0.0)
    detour_km = path_km - direct_km
    detour_km >= -1e-8 || error("station detour violates metric triangle inequality")
    visits = count(node -> node in stations, truck_route)
    return (
        feasible = true,
        makespan_h = checked.objective,
        station_visits = visits,
        truck_km = path_km,
        station_detour_km = max(0.0, detour_km),
        swap_service_minutes = 60.0 * visits * inst.swap_service_time,
    )
end
